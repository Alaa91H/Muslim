    /** Total number of ayahs in the mushaf. */
    const val TOTAL_AYAHS: Int = 6236

    /** Surah number (1..114) containing [globalNumber], or -1 when out of range. */
    fun surahOf(globalNumber: Int): Int {
        if (globalNumber < 1 || globalNumber > TOTAL_AYAHS) return -1
        var remaining = globalNumber
        for (i in AYAH_COUNTS.indices) {
            if (remaining <= AYAH_COUNTS[i]) return i + 1
            remaining -= AYAH_COUNTS[i]
        }
        return -1
    }

    /** Ayah number inside its surah (1-based) for [globalNumber], or -1. */
    fun ayahInSurah(globalNumber: Int): Int {
        val surah = surahOf(globalNumber)
        if (surah < 1) return -1
        var remaining = globalNumber
        for (i in 0 until surah - 1) remaining -= AYAH_COUNTS[i]
        return remaining
    }

    /** Display name of [surahNumber] (1..114), or empty when invalid. */
    fun surahName(surahNumber: Int): String =
        SURAH_NAMES.getOrNull(surahNumber - 1) ?: ""

    /** Compact reference like "البقرة 255" for [globalNumber], or empty. */
    fun referenceOf(globalNumber: Int): Pair<String, Int>? {
        val surah = surahOf(globalNumber)
        if (surah < 1) return null
        return surahName(surah) to ayahInSurah(globalNumber)
    }
