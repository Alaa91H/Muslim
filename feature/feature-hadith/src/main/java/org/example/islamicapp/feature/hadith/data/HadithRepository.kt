/**
 * The Forty Hadith of Imam an-Nawawi (الأربعون النووية) — every Muslim's
 * foundational companion collection (PROJECT_PROMPT.md §6 Phase 3).
 *
 * Ordering follows the widely printed arrangement of the collection.
 * Grades reflect the well-known verdicts of the hadith verifiers
 * (Al-Albani and others) on these famous narrations.
 */
@Singleton
class HadithRepository @Inject constructor() {

    val hadiths: List<Hadith> by lazy { build() }

    fun byId(id: String): Hadith? = hadiths.firstOrNull { it.id == id }

    fun search(query: String): List<Hadith> {
        val q = query.trim()
        if (q.isEmpty()) return hadiths
        return hadiths.filter {
            it.text.contains(q, ignoreCase = true) ||
                it.titleAr.contains(q, ignoreCase = true) ||
                it.narrator.contains(q, ignoreCase = true)
        }
    }

    /** Rotating "hadith of the day" — deterministic per day-of-year. */
    fun hadithOfTheDay(dayOfYear: Int): Hadith =
        hadiths[dayOfYear.mod(hadiths.size)]

